-- =====================================================================
-- Inventory Management System (IMS): database schema + sample data
-- Dialect: PostgreSQL 17 (works on 15+)
-- Design date: 2026-11-18
--
-- Notes
--  * The app (.NET 10, EF Core with snake_case naming) creates these same table
--    names through migrations; ASP.NET Core Identity adds its own columns to users.
--  * inventory_transactions and audit_log are APPEND-ONLY: the trigger
--    function forbid_change() rejects every UPDATE and DELETE.
--  * There is NO status column anywhere. A unit's status is derived from its
--    history (see views effective_transactions and unit_current_status).
--  * Timestamps without an offset are read in the session's TimeZone setting.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. users: one role per user; deactivated, never deleted
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(150) NOT NULL UNIQUE,
    password      VARCHAR(128) NOT NULL,               -- salted PBKDF2 hash only
    first_name    VARCHAR(150) NOT NULL DEFAULT '',
    last_name     VARCHAR(150) NOT NULL DEFAULT '',
    employee_no   VARCHAR(20)  NOT NULL UNIQUE,
    role          VARCHAR(20)  NOT NULL DEFAULT 'REPORT_VIEWER'
                  CHECK (role IN ('ADMIN', 'COMPONENT_TRACKER', 'RECEIVE_USER',
                                  'DELIVERY_USER', 'REPORT_VIEWER')),
    is_active     BOOLEAN      NOT NULL DEFAULT FALSE, -- self-registered users wait for Admin
    last_login    TIMESTAMPTZ,
    date_joined   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 2. Master data: products, components, points (soft delete when in use)
-- ---------------------------------------------------------------------
CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL CHECK (length(btrim(name)) >= 2),
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (is_deleted = (deleted_at IS NOT NULL))
);
-- name unique (ignoring case) among rows that are not deleted
CREATE UNIQUE INDEX ux_products_name_active ON products (lower(name)) WHERE NOT is_deleted;

CREATE TABLE components (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL CHECK (length(btrim(name)) >= 2),
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (is_deleted = (deleted_at IS NOT NULL))
);
CREATE UNIQUE INDEX ux_components_name_active ON components (lower(name)) WHERE NOT is_deleted;

CREATE TABLE points (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL CHECK (length(btrim(name)) >= 2),
    point_type  VARCHAR(10)  NOT NULL CHECK (point_type IN ('TRACK', 'RECEIVE', 'DELIVERY')),
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (is_deleted = (deleted_at IS NOT NULL))
);
CREATE UNIQUE INDEX ux_points_name_type_active ON points (lower(name), point_type) WHERE NOT is_deleted;

-- ---------------------------------------------------------------------
-- 3. units: identity of one physical unit; NO status column
-- ---------------------------------------------------------------------
CREATE TABLE units (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode        VARCHAR(32) NOT NULL UNIQUE CHECK (barcode ~ '^[A-Z0-9-]{6,32}$'),
    product_id     BIGINT      NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    registered_at  TIMESTAMPTZ NOT NULL,
    registered_by  BIGINT      NOT NULL REFERENCES users (id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 4. inventory_transactions: append-only history of every operation
-- ---------------------------------------------------------------------
CREATE TABLE inventory_transactions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id            BIGINT      NOT NULL REFERENCES units (id) ON DELETE RESTRICT,
    event_type         VARCHAR(20) NOT NULL
                       CHECK (event_type IN ('COMPONENT_TRACKED', 'RECEIVED', 'DELIVERED', 'REVERSED')),
    point_id           BIGINT      NOT NULL REFERENCES points (id) ON DELETE RESTRICT,
    component_id       BIGINT      REFERENCES components (id) ON DELETE RESTRICT,
    component_barcode  VARCHAR(32),
    reverses_id        BIGINT      UNIQUE REFERENCES inventory_transactions (id) ON DELETE RESTRICT,
    reason             TEXT        NOT NULL DEFAULT '',
    performed_by       BIGINT      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    occurred_at        TIMESTAMPTZ NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- component columns only (and always) on COMPONENT_TRACKED rows
    CONSTRAINT ck_tx_component_columns CHECK (
           (event_type = 'COMPONENT_TRACKED' AND component_id IS NOT NULL AND component_barcode IS NOT NULL)
        OR (event_type <> 'COMPONENT_TRACKED' AND component_id IS NULL AND component_barcode IS NULL)),
    -- a reversal points at the row it cancels and gives a reason of 5+ characters
    CONSTRAINT ck_tx_reversal CHECK (
           (event_type = 'REVERSED' AND reverses_id IS NOT NULL AND length(btrim(reason)) >= 5)
        OR (event_type <> 'REVERSED' AND reverses_id IS NULL))
);
CREATE INDEX ix_tx_unit_time         ON inventory_transactions (unit_id, occurred_at);
CREATE INDEX ix_tx_event_time        ON inventory_transactions (event_type, occurred_at);
CREATE INDEX ix_tx_component_barcode ON inventory_transactions (component_barcode);

-- Append-only: one function shared by both permanent tables
CREATE FUNCTION forbid_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END $$;

CREATE TRIGGER trg_tx_append_only BEFORE UPDATE OR DELETE ON inventory_transactions
    FOR EACH ROW EXECUTE FUNCTION forbid_change();

-- Insert-time rules: point type matches the event, a component barcode has
-- one owner at a time, and a reversal can never itself be reversed
CREATE FUNCTION check_transaction() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_point_type    text;
    v_expected_type text;
BEGIN
    IF NEW.event_type <> 'REVERSED' THEN
        SELECT point_type INTO v_point_type FROM points WHERE id = NEW.point_id;
        -- computed first: a CASE inside an IF condition would end the condition at its first THEN
        v_expected_type := CASE NEW.event_type
                               WHEN 'COMPONENT_TRACKED' THEN 'TRACK'
                               WHEN 'RECEIVED'          THEN 'RECEIVE'
                               WHEN 'DELIVERED'         THEN 'DELIVERY'
                           END;
        IF v_point_type IS DISTINCT FROM v_expected_type THEN
            RAISE EXCEPTION 'point type does not match the event';
        END IF;
    END IF;

    IF NEW.event_type = 'COMPONENT_TRACKED' AND EXISTS (
        SELECT 1 FROM inventory_transactions t
        WHERE t.event_type = 'COMPONENT_TRACKED'
          AND t.component_barcode = NEW.component_barcode
          AND NOT EXISTS (SELECT 1 FROM inventory_transactions r WHERE r.reverses_id = t.id)) THEN
        RAISE EXCEPTION 'component barcode % is already attached to a unit', NEW.component_barcode;
    END IF;

    IF NEW.event_type = 'REVERSED' AND
       (SELECT event_type FROM inventory_transactions WHERE id = NEW.reverses_id) = 'REVERSED' THEN
        RAISE EXCEPTION 'a reversal cannot be reversed';
    END IF;

    RETURN NEW;
END $$;

CREATE TRIGGER trg_tx_checks BEFORE INSERT ON inventory_transactions
    FOR EACH ROW EXECUTE FUNCTION check_transaction();

-- ---------------------------------------------------------------------
-- 5. audit_log: separate, append-only record of master-data/user changes and logins
-- ---------------------------------------------------------------------
CREATE TABLE audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     BIGINT REFERENCES users (id) ON DELETE RESTRICT,   -- NULL = system
    action       VARCHAR(30) NOT NULL
                 CHECK (action IN ('CREATE', 'UPDATE', 'DELETE', 'SOFT_DELETE', 'RESTORE',
                                   'ROLE_CHANGE', 'ACTIVATE', 'DEACTIVATE', 'PASSWORD_CHANGE',
                                   'PASSWORD_RESET', 'LOGIN', 'LOGOUT', 'LOGIN_FAILED')),
    entity_type  VARCHAR(30)  NOT NULL,
    entity_id    VARCHAR(40),
    entity_repr  VARCHAR(200) NOT NULL DEFAULT '',
    old_values   JSONB,             -- changed fields only; never password hashes
    new_values   JSONB,
    ip_address   INET,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_time   ON audit_log (created_at);
CREATE INDEX ix_audit_entity ON audit_log (entity_type, entity_id);

CREATE TRIGGER trg_audit_append_only BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION forbid_change();

-- ---------------------------------------------------------------------
-- 6. Derived state (read-only views; the application uses the same logic)
-- ---------------------------------------------------------------------
-- Rows still in effect: not a reversal, and not cancelled by one
CREATE VIEW effective_transactions AS
SELECT t.*
FROM inventory_transactions t
WHERE t.event_type <> 'REVERSED'
  AND NOT EXISTS (SELECT 1 FROM inventory_transactions r WHERE r.reverses_id = t.id);

-- Current status of every unit = its latest effective RECEIVED / DELIVERED row
CREATE VIEW unit_current_status AS
SELECT u.id          AS unit_id,
       u.barcode,
       p.name        AS product,
       CASE s.event_type WHEN 'DELIVERED' THEN 'DELIVERED'
                         WHEN 'RECEIVED'  THEN 'IN_STOCK'
                         ELSE 'REGISTERED' END AS status,
       pt.name       AS current_point,
       s.occurred_at AS since
FROM units u
JOIN products p ON p.id = u.product_id
LEFT JOIN (SELECT e.*, ROW_NUMBER() OVER (PARTITION BY e.unit_id
                                          ORDER BY e.occurred_at DESC, e.id DESC) AS rn
           FROM effective_transactions e
           WHERE e.event_type IN ('RECEIVED', 'DELIVERED')) s
       ON s.unit_id = u.id AND s.rn = 1
LEFT JOIN points pt ON pt.id = s.point_id;

-- Components currently attached to each unit
CREATE VIEW unit_attached_components AS
SELECT e.unit_id, c.name AS component, e.component_barcode, e.occurred_at AS attached_at
FROM effective_transactions e
JOIN components c ON c.id = e.component_id
WHERE e.event_type = 'COMPONENT_TRACKED';

